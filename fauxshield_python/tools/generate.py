"""Generates ``src/fauxshield/generated/`` from the shared API contract.

The contract is extracted from the server's generated Dart client by
``fauxshield_contract``, so this SDK cannot describe a method, parameter, or
model field the API does not have.

Run with: ``python tools/generate.py``
"""

from __future__ import annotations

import json
import keyword
import re
from pathlib import Path
from typing import Any, Dict, Iterable, List, Set, Tuple

HERE = Path(__file__).resolve().parent
PACKAGE_ROOT = HERE.parent
CONTRACT_PATH = PACKAGE_ROOT.parent / "fauxshield_contract" / "contract" / "api_contract.json"
OUT_DIR = PACKAGE_ROOT / "src" / "fauxshield" / "generated"

def snake_case(name: str) -> str:
    """``deleteImpact`` -> ``delete_impact``, ``apiKey`` -> ``api_key``."""
    first = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    second = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first)
    return second.lower()


def py_identifier(name: str) -> str:
    """A snake_case name that is legal Python: ``from`` -> ``from_``."""
    value = snake_case(name)
    if keyword.iskeyword(value):
        return "{}".format(value) + "_"
    return value


def py_type(type_name: str, model_names: Set[str], enum_names: Set[str]) -> str:
    """Maps a Dart type from the contract onto a Python annotation."""
    match = re.match(r"^List<(.+)>$", type_name)
    if match:
        return "List[{}]".format(py_type(match.group(1), model_names, enum_names))
    match = re.match(r"^Map<(.+),\s*(.+)>$", type_name)
    if match:
        return "Dict[{}, {}]".format(
            py_type(match.group(1), model_names, enum_names),
            py_type(match.group(2), model_names, enum_names),
        )

    primitives = {
        "String": "str",
        "int": "int",
        "double": "float",
        "num": "float",
        "bool": "bool",
        "DateTime": "str",
        "Duration": "float",
        "UuidValue": "str",
        "ByteData": "bytes",
        "dynamic": "Any",
        "Object": "Any",
    }
    if type_name in primitives:
        return primitives[type_name]
    if type_name in model_names or type_name in enum_names:
        return type_name
    return "Any"


def models_source(contract: Dict[str, Any]) -> str:
    model_names = {model["name"] for model in contract["models"]}
    enum_names = {value["name"] for value in contract["enums"]}

    lines: List[str] = [
        '"""Generated by tools/generate.py from the API contract. Do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "from typing import Any, Dict, List, Optional, TypedDict",
        "",
        "# Field names match the wire format, which is camelCase. Every key is",
        "# optional in the type because the API sends what it has: a field the",
        "# server has not filled in is simply absent from the JSON.",
        "",
    ]

    for model in contract["models"]:
        lines.append("")
        lines.append("class {}(TypedDict, total=False):".format(model["name"]))
        if not model["fields"]:
            lines.append('    """No fields."""')
            continue
        for field in model["fields"]:
            annotation = py_type(field["type"], model_names, enum_names)
            if field["nullable"]:
                annotation = "Optional[{}]".format(annotation)
            lines.append("    {}: {}".format(field["name"], annotation))

    for value in contract["enums"]:
        lines.append("")
        lines.append("")
        lines.append("class {}(str, Enum):".format(value["name"]))
        lines.append('    """Wire values as the API sends them."""')
        lines.append("")
        for member in value["values"]:
            lines.append('    {} = "{}"'.format(snake_case(member).upper(), member))

    lines.append("")
    return "\n".join(lines)


def resources_source(contract: Dict[str, Any]) -> str:
    model_names = {model["name"] for model in contract["models"]}
    enum_names = {value["name"] for value in contract["enums"]}

    imports: Set[str] = set()
    bodies: List[str] = []

    for endpoint in contract["endpoints"]:
        class_name = "{}Resource".format(endpoint["name"][0].upper() + endpoint["name"][1:])
        bodies.append("")
        bodies.append("")
        bodies.append("class {}:".format(class_name))
        bodies.append('    """The `{}` endpoint."""'.format(endpoint["name"]))
        bodies.append("")
        bodies.append("    def __init__(self, transport: Transport) -> None:")
        bodies.append("        self._transport = transport")

        for method in endpoint["methods"]:
            returns = py_type(method["returns"], model_names, enum_names)
            collect(returns, imports, model_names, enum_names)

            parameters: List[Tuple[str, str, bool, str]] = []
            for param in method["params"]:
                annotation = py_type(param["type"], model_names, enum_names)
                if param["nullable"]:
                    annotation = "Optional[{}]".format(annotation)
                collect(annotation, imports, model_names, enum_names)
                required = bool(param.get("required", False))
                parameters.append(
                    (
                        py_identifier(param["name"]),
                        annotation,
                        required,
                        param["name"],
                    )
                )

            payload = ", ".join(
                '"{}": {}'.format(original, local) for (local, _, _, original) in parameters
            )

            bodies.append("")
            bodies.append(
                "    def {}(self{}):".format(
                    snake_case(method["name"]), _signature(parameters)
                )
            )
            bodies.append('        """`{}.{}`."""'.format(endpoint["name"], method["name"]))
            bodies.append(
                '        return self._transport.call("{}", "{}", {{{}}})'.format(
                    endpoint["name"],
                    method["name"],
                    payload,
                )
            )

    header = [
        '"""Generated by tools/generate.py from the API contract. Do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Optional",
        "",
        "from ..transport import Transport",
        "from .models import {}".format(", ".join(sorted(imports)) or "Any"),
        "",
    ]
    return "\n".join(header + bodies) + "\n"


def _signature(parameters: Iterable[Tuple[str, str, bool, str]]) -> str:
    """Keyword-only arguments: a call reads as the API it describes.

    Required arguments come without a default, optional ones without a value, so
    a missing required argument is a ``TypeError`` from Python rather than a
    failed request.
    """
    parts: List[str] = []
    for (local, annotation, required, _original) in parameters:
        if required:
            parts.append("{}: {}".format(local, annotation))
        else:
            parts.append("{}: {} = None".format(local, annotation))
    if not parts:
        return ""
    return ", *, " + ", ".join(parts)


def collect(annotation: str, into: Set[str], model_names: Set[str], enum_names: Set[str]) -> None:
    for name in re.findall(r"[A-Z][A-Za-z0-9_]*", annotation):
        if name in model_names or name in enum_names:
            into.add(name)


def main() -> None:
    contract = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "__init__.py").write_text("", encoding="utf-8")
    (OUT_DIR / "models.py").write_text(models_source(contract), encoding="utf-8")
    (OUT_DIR / "resources.py").write_text(resources_source(contract), encoding="utf-8")
    methods = sum(len(endpoint["methods"]) for endpoint in contract["endpoints"])
    print(
        "Wrote {} models, {} enums, {} resources ({} methods) to {}".format(
            len(contract["models"]),
            len(contract["enums"]),
            len(contract["endpoints"]),
            methods,
            OUT_DIR,
        )
    )


if __name__ == "__main__":
    main()
