/// Assembles the documentation site: groups, pages, and reading order.
///
/// The API reference pages are built from the generated [docsApi], the written
/// pages come from the other files in this directory, and this file decides the
/// order a reader walks them in. Everything else — the sidebar, the search
/// index, the previous/next links, and the routes — is derived from that one
/// list, so a page cannot be linked without existing.
library;

import 'docs_guides.dart';
import 'docs_model.dart';
import 'docs_ops.dart';
import 'docs_reference.dart';
import 'api_reference.g.dart';

/// The documentation site, in reading order.
///
/// `docsApi` is generated by `tool/generate_docs.dart`; the endpoint pages
/// below are one per endpoint, in the order the contract lists them.
final DocsSite docsSite = _build();

DocsSite _build() {
  final api = docsApi;
  return DocsSite(
    api: api,
    groups: <DocsGroup>[
      DocsGroup(
        id: 'overview',
        title: 'Overview',
        pages: <DocsPage>[
          overviewPage(),
          conceptsPage(),
          architecturePage(),
        ],
      ),
      DocsGroup(
        id: 'getting-started',
        title: 'Getting started',
        pages: <DocsPage>[
          quickstartPage(),
          apiKeysPage(),
          firstRequestPage(),
          localDevelopmentPage(),
        ],
      ),
      DocsGroup(
        id: 'authentication',
        title: 'Authentication',
        pages: <DocsPage>[authenticationPage()],
      ),
      DocsGroup(
        id: 'api',
        title: 'API reference',
        pages: <DocsPage>[
          apiIndexPage(api),
          verificationFlowPage(),
          for (final endpoint in api.endpoints) apiEndpointPage(api, endpoint),
          apiModelsPage(api),
          apiEnumsPage(api),
        ],
      ),
      DocsGroup(
        id: 'sdk',
        title: 'SDKs',
        pages: <DocsPage>[
          sdkPage(api, 'dart'),
          sdkPage(api, 'node'),
          sdkPage(api, 'python'),
          sdkParityPage(api),
        ],
      ),
      DocsGroup(
        id: 'guides',
        title: 'Guides',
        pages: <DocsPage>[
          webhooksGuidePage(),
          offlineGuidePage(),
          errorHandlingGuidePage(),
          testingGuidePage(),
          productionGuidePage(),
        ],
      ),
      DocsGroup(
        id: 'cli',
        title: 'CLI',
        pages: <DocsPage>[cliPage()],
      ),
      DocsGroup(
        id: 'mcp',
        title: 'MCP',
        pages: <DocsPage>[mcpPage()],
      ),
      DocsGroup(
        id: 'reference',
        title: 'Reference',
        pages: <DocsPage>[
          errorCodesPage(),
          environmentPage(),
          glossaryPage(),
          changelogPage(),
        ],
      ),
    ],
  );
}

/// A page for a slug that does not exist.
///
/// It answers the question a reader actually has — "where is it?" — with the
/// search box, the groups, and the most likely destinations, instead of a bare
/// 404. The page asks crawlers not to index it, since it is not content.
DocsPage notFoundPage(DocsSite site, String slug) {
  final suggestions = site.pages.take(8);
  return DocsPage(
    slug: 'not-found',
    title: 'That page does not exist',
    description:
        'No documentation page lives at /docs/$slug. Nothing was broken on your '
        'side: the link is wrong, or the page moved.',
    group: site.groups.first.id,
    sections: <DocsSection>[
      DocsSection(
        id: 'try',
        title: 'Try one of these',
        html:
            '''
<ul class="docs-link-cards">
${suggestions.map((page) => '<li><a href="${page.path}"><strong>${page.title}</strong><span>${page.description}</span></a></li>').join()}
</ul>
<p>
  Or search: press <kbd>/</kbd> or <kbd>Ctrl</kbd>+<kbd>K</kbd> anywhere in
  these pages, and type what you are looking for.
</p>
''',
      ),
      DocsSection(
        id: 'status',
        title: 'If you followed a link from these docs',
        html: '''
<p>
  Every internal link in the portal is checked by a test in
  <code>fauxshield_server/test/unit/docs_link_test.dart</code>, so a broken
  one is a bug worth reporting:
  <a href="https://github.com/tope-olajide/fauxshield/issues">open an issue</a>.
</p>
''',
      ),
    ],
  );
}
