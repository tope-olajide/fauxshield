// Generates src/generated/{models,resources}.ts from the contract that
// fauxshield_contract extracts from the generated Dart client, so this SDK can
// never describe a method, parameter, or field the API does not have.
//
// Run with: npm run generate  (or node tools/generate.mjs)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, '..');
const contractPath = join(packageRoot, '..', 'fauxshield_contract', 'contract', 'api_contract.json');
const outDir = join(packageRoot, 'src', 'generated');

const contract = JSON.parse(readFileSync(contractPath, 'utf8'));

/** Maps a Dart type from the contract onto TypeScript. */
function tsType(type, nullable) {
  const base = (() => {
    const list = /^List<(.+)>$/.exec(type);
    if (list) return `${tsType(list[1], false)}[]`;

    const map = /^Map<(.+),\s*(.+)>$/.exec(type);
    if (map) return `Record<${tsType(map[1], false)}, ${tsType(map[2], false)}>`;

    if (type === 'String') return 'string';
    if (type === 'int' || type === 'double' || type === 'num') return 'number';
    if (type === 'bool') return 'boolean';
    if (type === 'DateTime') return 'string';
    if (type === 'Duration') return 'number';
    if (type === 'UuidValue') return 'string';
    if (type === 'ByteData') return 'Uint8Array';
    if (type === 'dynamic' || type === 'Object') return 'unknown';

    const callable = /^(.+) Function\(.*\)$/.exec(type);
    if (callable) return '(...args: unknown[]) => unknown';

    // Anything left is a model or enum name from this API.
    return type.replace('?', '');
  })();

  return nullable ? `${base} | null` : base;
}

/** `Product` -> `Product`, `ApiKeySecret` -> `ApiKeySecret`. */
const reservedNames = new Set(['Date', 'Error', 'String', 'Number', 'Boolean', 'Object', 'Record', 'Array']);

/** Builds the interfaces and enums file. */
function modelsFile() {
  const lines = [
    '/* Generated by tools/generate.mjs from the API contract. Do not edit. */',
    '',
    '// Model field names match the wire format, which is camelCase.',
    '',
  ];

  for (const model of contract.models) {
    if (!model.fields.length) {
      lines.push(`export type ${model.name} = Record<string, never>;`, '');
      continue;
    }
    lines.push(`export interface ${model.name} {`);
    for (const field of model.fields) {
      lines.push(`  ${field.name}${field.nullable ? '?' : ''}: ${tsType(field.type, field.nullable)};`);
    }
    lines.push('}', '');
  }

  for (const value of contract.enums) {
    lines.push(`export type ${value.name} = ${value.values.map((v) => `'${v}'`).join(' | ')};`, '');
    lines.push(`export const ${value.name} = {`);
    for (const v of value.values) {
      lines.push(`  ${v}: '${v}',`);
    }
    lines.push(`} as const;`, '');
  }

  for (const exception of contract.exceptions) {
    lines.push(`export interface ${exception.name}Body {`);
    for (const field of exception.fields) {
      lines.push(`  ${field.name}${field.nullable ? '?' : ''}: ${tsType(field.type, field.nullable)};`);
    }
    lines.push('}', '');
  }

  return `${lines.join('\n')}\n`;
}

/** Builds the resource classes: one per endpoint, one typed method per call. */
function resourcesFile() {
  const modelNames = new Set(contract.models.map((m) => m.name));
  const enumNames = new Set(contract.enums.map((e) => e.name));

  const typeFor = (type, nullable) => {
    const plain = type.replace('?', '');
    if (modelNames.has(plain) || enumNames.has(plain)) return tsType(type, nullable);
    return tsType(type, nullable);
  };

  const importNames = new Set();
  const body = [];

  const classNames = new Map();
  for (const endpoint of contract.endpoints) {
    const className = `${endpoint.name[0].toUpperCase()}${endpoint.name.slice(1)}Resource`;
    classNames.set(endpoint.name, { className, endpoint });
  }

  for (const { className, endpoint } of classNames.values()) {
    body.push(`/** The \`${endpoint.name}\` endpoint. */`, `export class ${className} {`);
    body.push('  constructor(private readonly transport: Transport) {}', '');
    for (const method of endpoint.methods) {
      const params = method.params.map((param) => {
        const t = typeFor(param.type, param.nullable);
        collectImports(t, importNames, modelNames, enumNames);
        return `${param.name}${param.required ? '' : '?'}: ${t}`;
      });
      collectImports(method.returns, importNames, modelNames, enumNames);
      const returns = typeFor(method.returns, false);
      // A call with nothing required can omit the object entirely; one with a
      // required argument must be given it, so there is no misleading default.
      const canOmit = method.params.every((param) => !param.required);
      body.push(`  /** ${endpoint.name}.${method.name} */`);
      if (method.params.length === 0) {
        body.push(`  ${method.name}(): Promise<${returns}> {`);
        body.push(
          `    return this.transport.call('${endpoint.name}', '${method.name}', {}) as Promise<${returns}>;`,
        );
        body.push('  }', '');
        continue;
      }
      body.push(`  ${method.name}(params: {`);
      for (const param of method.params) {
        const t = typeFor(param.type, param.nullable);
        body.push(`    ${param.name}${param.required ? '' : '?'}: ${t},`);
      }
      body.push(`  }${canOmit ? ' = {}' : ''}): Promise<${returns}> {`);
      body.push(`    return this.transport.call('${endpoint.name}', '${method.name}', params) as Promise<${returns}>;`);
      body.push('  }', '');
    }
    body.push('}', '');
  }

  const lines = [
    '/* Generated by tools/generate.mjs from the API contract. Do not edit. */',
    '',
    "import type { Transport } from '../transport.js';",
    `import type { ${[...importNames].sort().join(', ')} } from './models.js';`,
    '',
    ...body,
  ];
  return `${lines.join('\n').replace(/\n\n\n+/g, '\n\n')}\n`;
}

function collectImports(type, into, modelNames, enumNames) {
  const names = type.match(/[A-Z][A-Za-z0-9_]*/g) ?? [];
  for (const name of names) {
    if (reservedNames.has(name)) continue;
    if (modelNames.has(name) || enumNames.has(name)) into.add(name);
  }
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'models.ts'), modelsFile());
writeFileSync(join(outDir, 'resources.ts'), resourcesFile());

const methods = contract.endpoints.reduce((sum, endpoint) => sum + endpoint.methods.length, 0);
console.log(
  `Wrote ${contract.models.length} models, ${contract.enums.length} enums, ` +
    `${contract.endpoints.length} resources (${methods} methods) to src/generated/`,
);
